#!/usr/bin/env node
// Independent Node/OpenSSL vectors. Run only in GitHub-hosted Actions.
'use strict';
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

if (process.env.GITHUB_ACTIONS !== 'true' || process.env.RUNNER_ENVIRONMENT !== 'github-hosted'
    || process.env.GITHUB_REPOSITORY !== 'ZHanry/NestLink') {
  throw new Error('R02: derive network reference vectors in GitHub-hosted Actions only');
}
const source = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (source !== process.env.GITHUB_SHA || !/^[a-f0-9]{40}$/.test(source)) throw new Error('Source mismatch');
const output = path.resolve(process.argv[2] || '');
const temporary = path.resolve(process.env.RUNNER_TEMP);
const relative = path.relative(temporary, output);
if (!relative || relative.startsWith('..') || path.isAbsolute(relative) || fs.existsSync(output)) {
  throw new Error('Output must be a new owned child of RUNNER_TEMP');
}
fs.mkdirSync(output);

const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const seed = Buffer.alloc(32, 42); // Fixed public test seed; never a deployed key.
const derived = Buffer.from(crypto.hkdfSync('sha256', seed,
  Buffer.from('NestLink/network/v1/authority-keys'), Buffer.from('network-authority-ed25519'), 32));
const authority = crypto.createPrivateKey({ key: Buffer.concat([
  Buffer.from('302e020100300506032b657004220420', 'hex'), derived,
]), format: 'der', type: 'pkcs8' });
const publicKey = crypto.createPublicKey(authority).export({ format: 'der', type: 'spki' }).subarray(-32);
// RFC 8032 section 7.1, test 1 public key, independent of the authority key.
const memberKey = Buffer.from('d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a', 'hex');
const memberPeer = Buffer.from(sha256(memberKey), 'hex');
const scope = {
  schema_version: 1,
  deployment_id: '10000000-0000-4000-8000-000000000001',
  space_id: '20000000-0000-4000-8000-000000000002',
  grant_id: '30000000-0000-4000-8000-000000000003',
  policy_epoch: 7, not_before_ms: 1000, expires_at_ms: 2000,
};
const claims = {
  kind: 'membership', claims: {
    scope,
    installation_id: '40000000-0000-4000-8000-000000000004',
    peer: [...memberPeer], public_key: [...memberKey], membership_epoch: 3, role: 'member',
  },
};
const text = JSON.stringify(claims);
const bytes = Buffer.from(text, 'utf8');
const length = Buffer.alloc(4);
length.writeUInt32BE(bytes.length);
const message = Buffer.concat([Buffer.from('NestLink/network/v1/membership\0'), length, bytes]);
const signature = crypto.sign(null, message, authority);
if (!crypto.verify(null, message, crypto.createPublicKey(authority), signature)) throw new Error('Reference signature failed');
const vector = {
  schema_version: 1,
  generator: 'Node node:crypto Ed25519/OpenSSL; independent from Rust implementation',
  public_test_master_seed_hex: seed.toString('hex'),
  authority_public_key_hex: publicKey.toString('hex'),
  member_public_key_hex: memberKey.toString('hex'),
  canonical_claims_utf8: text,
  signing_message_sha256: sha256(message),
  signature_hex: signature.toString('hex'),
};
const vectorBytes = Buffer.from(JSON.stringify(vector, null, 2) + '\n');
const committed = path.join(process.cwd(), 'crates/identity/tests/fixtures/network-v1-reference.json');
if (fs.existsSync(committed) && !fs.readFileSync(committed).equals(vectorBytes)) {
  throw new Error('Committed reference vector differs from independently regenerated bytes');
}
fs.writeFileSync(path.join(output, 'network-v1-reference.json'), vectorBytes);
// Independently construct every grant kind and the digest references between
// them. Neither Rust serialization nor its signing implementation is invoked.
const hashBytes = value => Buffer.from(sha256(value), 'hex');
const scopeFor = id => ({ ...scope, grant_id: `30000000-0000-4000-8000-${id.toString(16).padStart(12, '0')}` });
const domains = { membership: 'membership', connectivity: 'connectivity', path: 'path',
  transit: 'transit', route_export: 'route-export', network_access: 'network-access' };
const signingMessage = value => {
  const encoded = Buffer.from(JSON.stringify(value));
  const size = Buffer.alloc(4);
  size.writeUInt32BE(encoded.length);
  return Buffer.concat([Buffer.from(`NestLink/network/v1/${domains[value.kind]}\0`), size, encoded]);
};
const grantDigest = value => hashBytes(Buffer.concat([
  Buffer.from('NestLink/network/v1/grant-digest\0'), publicKey, signingMessage(value),
]));
const secondMemberKey = Buffer.from('3d4017c3e843895a92b70aa74d1b7ebc9c982ccf2ec4968cc0cd55f12af4660c', 'hex');
const secondMember = { kind: 'membership', claims: {
  scope: scopeFor(5), installation_id: '40000000-0000-4000-8000-000000000005',
  peer: [...hashBytes(secondMemberKey)], public_key: [...secondMemberKey], membership_epoch: 2, role: 'guest',
} };
const members = [claims, secondMember].sort((a, b) => Buffer.compare(Buffer.from(a.claims.peer), Buffer.from(b.claims.peer)));
const peers = { first: members[0].claims.peer, second: members[1].claims.peer };
const connectivity = { kind: 'connectivity', claims: {
  scope: scopeFor(6), peers, purpose: 'remote_control',
  membership_digests: members.map(value => [...grantDigest(value)]),
  business_grant_digest: [...hashBytes(Buffer.from('independent-public-business-fixture'))],
} };
const relay = [...hashBytes(Buffer.alloc(32, 20))];
const pathGrant = { kind: 'path', claims: {
  scope: scopeFor(7), peers, purpose: 'remote_control',
  connectivity_grant_digest: [...grantDigest(connectivity)],
  policy: { allow_direct: true, relays: [relay], max_hops: 1 },
} };
const group = hashBytes(Buffer.concat([
  Buffer.from('NestLink/network/v1/transport-group\0'), publicKey, signingMessage(pathGrant),
]));
const transit = { kind: 'transit', claims: {
  scope: scopeFor(8), peers, transport_group: [...group],
  route_id: '50000000-0000-4000-8000-000000000001', relay,
  previous: peers.first, next: peers.second, remaining_hops: 1, byte_limit: 65536,
} };
const routeExport = { kind: 'route_export', claims: {
  scope: scopeFor(9), gateway: relay,
  prefixes: [{ network: '10.42.0.0', prefix_len: 24 }, { network: 'fd42::', prefix_len: 64 }],
} };
const networkAccess = { kind: 'network_access', claims: {
  scope: scopeFor(10), source: peers.first, destination: peers.second,
  source_prefixes: [{ network: '10.43.0.1', prefix_len: 32 }],
  destination_prefixes: [{ network: '10.42.0.0', prefix_len: 24 }],
  rules: [{ protocol: 'tcp', direction: 'inbound', ports: [22, 22] },
    { protocol: 'udp', direction: 'outbound', ports: [53, 53] },
    { protocol: 'icmp_v6', direction: 'inbound', ports: null }],
  byte_limit: 65536,
} };
const allVectors = {
  schema_version: 1, generator: vector.generator,
  public_test_master_seed_hex: seed.toString('hex'), authority_public_key_hex: publicKey.toString('hex'),
  transport_group_hex: group.toString('hex'),
  vectors: [...members, connectivity, pathGrant, transit, routeExport, networkAccess].map(value => {
    const signedMessage = signingMessage(value);
    const signed = crypto.sign(null, signedMessage, authority);
    if (!crypto.verify(null, signedMessage, crypto.createPublicKey(authority), signed)) {
      throw new Error('Independent grant signature self-verification failed');
    }
    return { kind: value.kind, canonical_claims_utf8: JSON.stringify(value),
      signing_message_sha256: sha256(signedMessage), grant_digest_hex: grantDigest(value).toString('hex'),
      signature_hex: signed.toString('hex') };
  }),
};
const allBytes = Buffer.from(JSON.stringify(allVectors, null, 2) + '\n');
const allName = 'network-v1-all-grants.json';
const committedAll = path.join(process.cwd(), 'crates/identity/tests/fixtures', allName);
if (fs.existsSync(committedAll) && !fs.readFileSync(committedAll).equals(allBytes)) {
  throw new Error('Committed all-grant vectors differ from independently regenerated bytes');
}
fs.writeFileSync(path.join(output, allName), allBytes);
const receipt = {
  schema_version: 1, purpose: 'independent-network-contract-vector-generation-only',
  source_revision: source, workflow: process.env.GITHUB_WORKFLOW,
  workflow_sha: process.env.GITHUB_WORKFLOW_SHA, job: process.env.GITHUB_JOB,
  run_id: process.env.GITHUB_RUN_ID, run_attempt: process.env.GITHUB_RUN_ATTEMPT,
  runner: { environment: process.env.RUNNER_ENVIRONMENT, os: process.env.RUNNER_OS, arch: process.env.RUNNER_ARCH },
  runtime: process.version, openssl: process.versions.openssl,
  file: { name: 'network-v1-reference.json', bytes: vectorBytes.length, sha256: sha256(vectorBytes) },
  additional_files: [{ name: allName, bytes: allBytes.length, sha256: sha256(allBytes) }],
  acceptance_claims: [],
};
fs.writeFileSync(path.join(output, 'vector-build-provenance.json'), JSON.stringify(receipt, null, 2) + '\n');
console.log(JSON.stringify(receipt));
